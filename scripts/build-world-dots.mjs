// Generates src/content/world-dots.ts: a dot-matrix world map as one SVG path.
// Run: node scripts/build-world-dots.mjs   (only needed if the grid changes)
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);

// Equirectangular, cropped to inhabited latitudes.
const W = 1000;
const LAT_TOP = 78;
const LAT_BOTTOM = -56;
const STEP = 2.4; // degrees between dots
const H = Math.round((W * (LAT_TOP - LAT_BOTTOM)) / 360);

const x = (lon) => ((lon + 180) / 360) * W;
const y = (lat) => ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H;

let d = "";
let count = 0;
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) {
      d += `M${x(lon).toFixed(1)} ${y(lat).toFixed(1)}h0`;
      count++;
    }
  }
}

writeFileSync(
  "src/content/world-dots.ts",
  `// Generated by scripts/build-world-dots.mjs. Do not edit.\n` +
    `// ${count} dots, equirectangular, ${STEP}° grid, latitudes ${LAT_BOTTOM}..${LAT_TOP}.\n\n` +
    `export const worldMap = {\n  width: ${W},\n  height: ${H},\n  latTop: ${LAT_TOP},\n  latBottom: ${LAT_BOTTOM},\n  dots: "${d}",\n};\n`,
);
console.log(`${count} dots, ${W}x${H}, ${(d.length / 1024).toFixed(1)} KB`);
